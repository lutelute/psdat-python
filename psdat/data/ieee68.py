    """Build the 68-bus MATPOWER bus array with flat-start voltages."""
    # [BUS_I, TYPE, PD, QD, GS, BS, AREA, VM, VA, BASE_KV, ZONE, VMAX, VMIN]
    n  = 68
    buses = np.zeros((n, 13))
    for i in range(n):
        buses[i, 0]  = i + 1        # bus number
        buses[i, 6]  = 1            # area
        buses[i, 7]  = 1.0          # VM flat start
        buses[i, 8]  = 0.0          # VA flat start
        buses[i, 9]  = 0.0          # BASE_KV (not used here)
        buses[i, 10] = 1            # zone
        buses[i, 11] = 1.1          # VMAX
        buses[i, 12] = 0.9          # VMIN


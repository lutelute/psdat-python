def get_system() -> Dict:
    """Return the complete IEEE 68-bus system as a dict.

    Returns
    -------
    sys : dict
        'baseMVA' — float
        'ws'      — float
        'bus'     — ndarray (68, 13), MATPOWER bus array
        'branch'  — ndarray (83, 13), MATPOWER branch array
        'gen'     — ndarray (16, 10), MATPOWER generator array
        'MD'      — ndarray (14, 16), machine dynamic data
        'ED'      — ndarray (8, 16),  exciter data
        'TD'      — ndarray (3, 16),  turbine data
        'params'  — list of 16 MachineParams objects
    """
    return {
        'baseMVA': BASEMVA,
        'ws':      WS,
        'bus':     BUS.copy(),
        'branch':  BRANCH.copy(),
        'gen':     GEN.copy(),
        'MD':      MD.copy(),
        'ED':      ED.copy(),
        'TD':      TD.copy(),
        'params':  get_machine_params(),
    }


def get_machine_params() -> List[MachineParams]:
    """Return list of 16 MachineParams for the IEEE 68-bus generators.

    Returns
    -------
    params : list of MachineParams, length 16
    """
    params = []
    for g in range(16):
        p = MachineParams(
            H     = float(MD[0,  g]),
            Dm    = float(MD[1,  g]),
            Xd    = float(MD[2,  g]),
            Xdp   = float(MD[3,  g]),
            Xdpp  = float(MD[4,  g]),
            Xq    = float(MD[5,  g]),
            Xqp   = float(MD[6,  g]),
            Xqpp  = float(MD[7,  g]),
            Td0p  = float(MD[8,  g]),
            Td0pp = float(MD[9,  g]),
            Tq0p  = float(MD[10, g]),
            Tq0pp = float(MD[11, g]),
            Rs    = float(MD[12, g]),
            Xls   = float(MD[13, g]),
            KA    = float(ED[0,  g]),
            TA    = float(ED[1,  g]),
            KE    = float(ED[2,  g]),
            TE    = float(ED[3,  g]),
            KF    = float(ED[4,  g]),
            TF    = float(ED[5,  g]),
            Ax    = float(ED[6,  g]),
            Bx    = float(ED[7,  g]),
            TCH   = float(TD[0,  g]),
            TSV   = float(TD[1,  g]),
            RD    = float(TD[2,  g]),
            ws    = WS,
        )
        params.append(p)
    return params
